#!/usr/bin/env python3
"""Re-execute unchanged own TS + exact locked npm libraries without OS effects."""
import pathlib,tempfile,shutil,subprocess
v=pathlib.Path(__file__).resolve().parents[1];(v/'work').mkdir(exist_ok=True)
with tempfile.TemporaryDirectory(dir=v/'work',prefix='oracle-verify-')as folder:
    root=pathlib.Path(folder);shutil.copytree(v/'oracle',root/'oracle');(root/'data').mkdir()
    for name in ['own','marked15']:shutil.copytree(v/'fixtures'/name,root/'fixtures'/name)
    for script in ['export-marked.cjs','export-highlight.cjs','generate-cases.cjs']:
        subprocess.run(['node',str(root/'oracle'/script)],check=True)
    files=['data/marked15-inline-tag.regex','data/marked15-block-html.regex','data/highlight-11.11.1.json','oracle/callback-inventory.json','oracle/cases.json']
    for p in files:assert (root/p).read_bytes()==(v/p).read_bytes(),p+' regenerated bytes differ'
print('Original TS/locked-library oracle and declarative data reproduce exactly')
